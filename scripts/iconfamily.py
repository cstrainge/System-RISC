#!/usr/bin/env python3
"""iconfamily.py — one icon family <-> PNG, for System RISC resources.json.

A new, standalone script. iconconvert.py is left untouched; this one
handles the case iconconvert.py does not: a whole family (ICN#, icl8,
ics#, ics8) in a resources.json, with a palette you choose, in both
directions, with the same file names both ways so export -> edit in
Aseprite -> import round-trips without renaming.

Family:
  ICN#  32x32 1-bit: 256 bytes = 128 bitmap + 128 mask
  icl8  32x32 8-bit: 1024 bytes of palette indices
  ics#  16x16 1-bit: 64 bytes = 32 bitmap + 32 mask
  ics8  16x16 8-bit: 256 bytes of palette indices

Usage — export (resources.json -> PNGs, hex or file payloads):
  python3 iconfamily.py export --resources extensions/host-clipboard/resources.json \\
      --id 128 --palette System7-8BitStd.gpl --family clipboard --out ./png
  # writes clipboard-32-color.png, clipboard-32-1bit.png,
  #        clipboard-16-color.png, clipboard-16-1bit.png

Usage — import (PNGs -> resources.json, validated, then written back):
  python3 iconfamily.py import --resources extensions/host-clipboard/resources.json \\
      --id 128 --palette System7-8BitStd.gpl --png-dir ./temp --family clipboard
  # without --out, updates resources.json in place and leaves a
  # resources.json.bak copy of the original beside it.
  # with --out new.json, writes the updated manifest there instead.

Palette: --palette names a file, or --repo names a System RISC checkout
and clut 8 is used. Palette formats: .gpl (GIMP), .pal (JASC), .act
(768 bytes), .hex (one #rrggbb per line), or a classic clut .bin.
A palette with fewer than 256 entries cannot be used for icl8/ics8.

Import is strict by default, and nothing is written until every check
passes:
  * PNG sizes must be exact (32x32 / 16x16). No silent rescaling.
  * Every opaque colour pixel must be exactly a palette colour.
    Use --snap to snap off-palette colours to the nearest palette
    colour instead, with a report of every snap.
  * A 1-bit PNG must be black/white only.
  * Colour transparency and 1-bit mask transparency must agree
    (the runtime colours through the 1-bit mask, so a mismatch is a
    Finder/startup surprise, not a PNG detail).
  * The generated bytes are decoded back exactly as the runtime does
    and compared pixel-for-pixel with the input PNGs. A mismatch
    aborts the write.
  * BNDL/FREF is checked and reported: if no bundle in the manifest
    maps a file type to this id, Finder/startup will fall back to the
    theme icon instead of showing this family.

Runtime rules mirrored here (system/src/toolbox/quickdraw/icons.rs):
  * ICN# exactly 256 bytes, ics# exactly 64, icl8 exactly 1024,
    ics8 exactly 256. A colour resource without its 1-bit mask is a
    MissingMask error, and a malformed family can refuse an extension
    at startup instead of falling back.
  * Colour indices are interpreted against clut 8 at runtime. If the
    palette you pass differs from repo clut 8, import warns with the
    first differing indices, because Aseprite colours would not be
    Finder colours.
"""
import argparse, json, os, re, shutil, struct, sys
from PIL import Image

TYPEHEX = {"ICN#": "49434e23", "icl8": "69636c38", "ics#": "69637323",
           "ics8": "69637338", "clut": "636c7574"}
FAMILY = [("ICN#", 32, 256), ("icl8", 32, 1024),
          ("ics#", 16, 64), ("ics8", 16, 256)]
MONO = {32: "ICN#", 16: "ics#"}
COLOR = {32: "icl8", 16: "ics8"}

class ConvertError(Exception):
    pass

def load_palette_repo(repo):
    path = os.path.join(repo, "system/assets/visual", TYPEHEX["clut"] + "-8.bin")
    data = open(path, "rb").read()
    pal = []
    for i in range(256):
        _, r, g, b = struct.unpack(">HHHH", data[8 + i * 8: 16 + i * 8])
        pal.append((r >> 8, g >> 8, b >> 8))
    assert pal[0] == (255, 255, 255) and pal[255] == (0, 0, 0)
    return pal

def load_palette_file(path):
    ext = os.path.splitext(path)[1].lower()
    if ext == ".gpl":
        pal = []
        for line in open(path, encoding="utf-8", errors="replace"):
            line = line.strip()
            if not line or line.startswith(("GIMP", "Name:", "Columns:", "#")):
                continue
            parts = line.split()
            if len(parts) < 3:
                continue
            try:
                pal.append(tuple(int(parts[i]) for i in range(3)))
            except ValueError:
                continue
        if not pal:
            raise ConvertError(f"no colours found in palette {path}")
        return pal
    if ext == ".pal":
        lines = [l.strip() for l in open(path, encoding="utf-8", errors="replace")]
        if not lines or lines[0] != "JASC-PAL":
            raise ConvertError(f"{path} is not a JASC-PAL file")
        pal = []
        for line in lines[3:]:
            if line:
                pal.append(tuple(int(x) for x in line.split()[:3]))
        return pal
    if ext == ".act":
        data = open(path, "rb").read()
        if len(data) < 768:
            raise ConvertError(f".act palette {path} is {len(data)} bytes, expected >= 768")
        return [tuple(data[i * 3:i * 3 + 3]) for i in range(256)]
    if ext == ".hex":
        pal = []
        for line in open(path, encoding="utf-8", errors="replace"):
            line = line.strip()
            if line.startswith("#") and len(line) == 7:
                pal.append(tuple(int(line[i:i + 2], 16) for i in (1, 3, 5)))
        if not pal:
            raise ConvertError(f"no #rrggbb colours found in {path}")
        return pal
    if ext == ".bin":
        data = open(path, "rb").read()
        if len(data) < 8 + 256 * 8:
            raise ConvertError(f"clut .bin {path} is too short for 256 entries")
        pal = []
        for i in range(256):
            _, r, g, b = struct.unpack(">HHHH", data[8 + i * 8: 16 + i * 8])
            pal.append((r >> 8, g >> 8, b >> 8))
        return pal
    raise ConvertError(f"unknown palette format for {path} "
                       f"(use .gpl, .pal, .act, .hex, or a clut .bin)")

def resolve_palette(palette_path, repo):
    if palette_path:
        return load_palette_file(palette_path), palette_path
    if repo:
        return load_palette_repo(repo), "repo clut 8"
    raise ConvertError("a palette is required: pass --palette, or --repo for clut 8")

def load_manifest(resources_path):
    with open(resources_path, encoding="utf-8") as f:
        man = json.load(f)
    if not isinstance(man, dict) or not isinstance(man.get("resources"), list):
        raise ConvertError(f"{resources_path} is not a resources.json "
                           f"(expected a dict with a 'resources' list)")
    return man

def manifest_resource_bytes(man, base_dir, typ, iid):
    for r in man["resources"]:
        if r.get("type") == typ and r.get("id") == iid:
            p = r.get("payload", {})
            if p.get("format") == "hex":
                try:
                    return bytes.fromhex(p["hex"])
                except ValueError:
                    raise ConvertError(f"{typ} {iid}: payload hex is not valid hex")
            if p.get("format") == "file":
                path = os.path.join(base_dir, p["path"])
                try:
                    with open(path, "rb") as f:
                        return f.read()
                except OSError as e:
                    raise ConvertError(f"{typ} {iid}: cannot read payload file {path}: {e}")
            raise ConvertError(f"{typ} {iid}: unsupported payload format "
                               f"{p.get('format')!r} (expected 'hex' or 'file')")
    return None

def bits_to_alpha(bmp, mask, w, h, rowbytes):
    img = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    px = img.load()
    for y in range(h):
        for x in range(w):
            m = (mask[y * rowbytes + x // 8] >> (7 - x % 8)) & 1
            b = (bmp[y * rowbytes + x // 8] >> (7 - x % 8)) & 1
            if m:
                v = 0 if b else 255
                px[x, y] = (v, v, v, 255)
    return img

def color_icon(idx_bytes, icn_bytes, pal, size):
    rb = size // 8
    img = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    px = img.load()
    bmp = icn_bytes[: size * rb]
    mask = icn_bytes[size * rb:]
    for y in range(size):
        for x in range(size):
            m = (mask[y * rb + x // 8] >> (7 - x % 8)) & 1
            if m:
                px[x, y] = pal[idx_bytes[y * size + x]] + (255,)
    return img

def do_export(args):
    man = load_manifest(args.resources)
    base_dir = os.path.dirname(os.path.abspath(args.resources))
    pal, _ = resolve_palette(args.palette, args.repo)
    data = {}
    for typ, size, length in FAMILY:
        raw = manifest_resource_bytes(man, base_dir, typ, args.id)
        if raw is None:
            continue
        if len(raw) != length:
            raise ConvertError(f"{typ} {args.id}: expected {length} bytes, got {len(raw)}")
        data[typ] = raw
    if not data:
        raise ConvertError(f"no icon resources with id {args.id} in {args.resources}")
    for size in (32, 16):
        if COLOR[size] in data and MONO[size] not in data:
            raise ConvertError(f"{COLOR[size]} {args.id} is present but its 1-bit mask "
                               f"{MONO[size]} is missing; the runtime rejects a colour "
                               f"icon family without a mask (MissingMask)")
    os.makedirs(args.out, exist_ok=True)
    written = []
    def save(img, name):
        path = os.path.join(args.out, name)
        img.save(path); written.append(path)
    if args.family:
        cname = lambda size: f"{args.family}-{size}-color.png"
        bname = lambda size: f"{args.family}-{size}-1bit.png"
    else:
        tag = f"m{-args.id}" if args.id < 0 else str(args.id)
        cname = lambda size: f"icon-{tag}-{size}-color.png"
        bname = lambda size: f"icon-{tag}-{size}-1bit.png"
    for size in (32, 16):
        mono, color = MONO[size], COLOR[size]
        if color in data:
            save(color_icon(data[color], data[mono], pal, size), cname(size))
        if mono in data:
            raw = data[mono]; rb = size // 8
            save(bits_to_alpha(raw[:size * rb], raw[size * rb:], size, size, rb),
                 bname(size))
    print("\n".join(written))

def nearest(pal, rgb):
    best, bd = 0, None
    for i, c in enumerate(pal):
        d = sum((a - b) ** 2 for a, b in zip(c, rgb))
        if bd is None or d < bd:
            best, bd = i, d
    return best

def _load_png_exact(path, size):
    try:
        img = Image.open(path)
    except OSError as e:
        raise ConvertError(f"cannot open {path}: {e}")
    img = img.convert("RGBA")
    if img.size != (size, size):
        raise ConvertError(f"{path}: expected {size}x{size}, got "
                           f"{img.size[0]}x{img.size[1]}; iconfamily never "
                           f"rescales, export the PNG at native size")
    return img

def _mono_bytes(img, size, snap, label):
    rb = size // 8
    bmp = bytearray(size * rb); mask = bytearray(size * rb)
    px = img.load()
    bad = []
    for y in range(size):
        for x in range(size):
            r, g, b, a = px[x, y]
            if a < 128:
                continue
            if max(r, g, b) - min(r, g, b) > 16 and not snap:
                if len(bad) < 10:
                    bad.append(f"({x},{y}) rgb=({r},{g},{b})")
                continue
            mask[y * rb + x // 8] |= 1 << (7 - x % 8)
            if (0.299 * r + 0.587 * g + 0.114 * b) < 170:
                bmp[y * rb + x // 8] |= 1 << (7 - x % 8)
    if bad:
        raise ConvertError(f"{label}: not a 1-bit image: {len(bad)}+ coloured "
                           f"opaque pixels, e.g. {', '.join(bad)}; a 1-bit PNG "
                           f"must be black/white only (use --snap to force "
                           f"luminance conversion)")
    if not any(mask):
        raise ConvertError(f"{label}: mask is empty, the icon would be invisible")
    return bytes(bmp) + bytes(mask), bytes(mask)

def _color_bytes(img, mono_mask, pal, size, snap, label, report):
    index_of = {}
    duplicates = []
    for i, c in enumerate(pal):
        if c in index_of:
            duplicates.append((c, index_of[c], i))
        else:
            index_of[c] = i
    if duplicates:
        report.append(f"palette has duplicate colours, first index wins, "
                      f"e.g. {duplicates[0][0]} at {duplicates[0][1]} and {duplicates[0][2]}")
    idx = bytearray(size * size)
    rb = size // 8
    px = img.load()
    bad = []
    snaps = []
    for y in range(size):
        for x in range(size):
            m = (mono_mask[y * rb + x // 8] >> (7 - x % 8)) & 1
            r, g, b, a = px[x, y]
            if not m:
                if a >= 128 and len(bad) < 10:
                    bad.append(f"({x},{y}) opaque in colour PNG but "
                               f"transparent in 1-bit mask")
                continue
            if a < 128:
                if len(bad) < 10:
                    bad.append(f"({x},{y}) transparent in colour PNG but "
                               f"masked in by the 1-bit mask")
                continue
            rgb = (r, g, b)
            if rgb in index_of:
                idx[y * size + x] = index_of[rgb]
            elif snap:
                n = nearest(pal, rgb)
                idx[y * size + x] = n
                if len(snaps) < 10:
                    snaps.append(f"({x},{y}) {rgb} -> palette {n} {pal[n]}")
            elif len(bad) < 10:
                bad.append(f"({x},{y}) rgb={rgb} not in palette")
    if bad:
        raise ConvertError(f"{label}: {len(bad)}+ problems, e.g. "
                           f"{'; '.join(bad)}; fix the PNG in Aseprite with "
                           f"the palette loaded, or rerun with --snap")
    if snaps:
        report.append(f"{label}: snapped {len(snaps)} off-palette colours, "
                      f"e.g. {'; '.join(snaps)}")
    return bytes(idx)

def _check_bndl(man, base_dir, iid):
    def u16(data, off):
        return struct.unpack(">H", data[off:off + 2])[0]
    def decode_bundle(data):
        if len(data) < 8:
            raise ConvertError("BNDL too short")
        sig = data[:4]; count = u16(data, 6) + 1; cur = 8; maps = {}
        for _ in range(count):
            kind = data[cur:cur + 4]; n = u16(data, cur + 4) + 1; cur += 6
            entries = []
            for _ in range(n):
                entries.append((u16(data, cur), u16(data, cur + 2))); cur += 4
            maps[kind] = entries
        return sig, maps
    def decode_fref(data):
        if len(data) < 7:
            raise ConvertError("FREF too short")
        return data[:4], u16(data, 4)
    creator = man.get("creator")
    for r in man["resources"]:
        if r.get("type") != "BNDL":
            continue
        try:
            raw = manifest_resource_bytes(man, base_dir, "BNDL", r["id"])
            sig, maps = decode_bundle(raw)
        except ConvertError as e:
            return f"BNDL {r['id']}: cannot parse ({e})"
        if creator and sig.decode("latin-1") != creator:
            continue
        frefs = maps.get(b"FREF", []); icns = dict(maps.get(b"ICN#", []))
        for _, fref_id in frefs:
            fraw = manifest_resource_bytes(man, base_dir, "FREF", fref_id)
            if fraw is None:
                continue
            ftype, local = decode_fref(fraw)
            if icns.get(local) == iid:
                return (f"BNDL {r['id']} (creator {sig.decode('latin-1')}): "
                        f"file type {ftype.decode('latin-1')} local {local} "
                        f"-> ICN# {iid}; this id is the one Finder and "
                        f"startup will resolve")
    return (f"no BNDL/FREF mapping in this manifest resolves to id {iid}; "
            f"Finder/startup may fall back to the theme icon instead "
            f"of showing this family")

def _symbol_for(man, typ, iid, family):
    existing = {r["symbol"] for r in man["resources"] if r.get("symbol")}
    base = None
    for r in man["resources"]:
        if r.get("type") in ("ICN#", "ics#") and r.get("id") == iid and r.get("symbol"):
            base = r["symbol"]
            break
    if base:
        stem = re.sub(r"_ICON$", "", base)
        suffix = {"ICN#": "_ICON", "icl8": "_ICON_COLOR",
                  "ics#": "_ICON_SMALL", "ics8": "_ICON_SMALL_COLOR"}[typ]
        cand = stem + suffix
    else:
        stem = re.sub(r"[^A-Z0-9_]", "_", (family or f"ICON_{iid}").upper())
        cand = f"{stem}_{typ.replace('#', 'HASH').upper()}_{iid}"
    if cand not in existing:
        return cand
    n = 2
    while f"{cand}_{n}" in existing:
        n += 1
    return f"{cand}_{n}"

def do_import(args):
    man = load_manifest(args.resources)
    base_dir = os.path.dirname(os.path.abspath(args.resources))
    pal, pal_name = resolve_palette(args.palette, args.repo)
    if len(pal) < 256:
        raise ConvertError(f"palette {pal_name} has {len(pal)} colours, "
                           f"icl8/ics8 need 256")
    if args.repo:
        repo_pal = load_palette_repo(args.repo)
        diffs = [(i, pal[i], repo_pal[i]) for i in range(256) if pal[i] != repo_pal[i]]
        if diffs:
            print(f"WARNING: palette {pal_name} differs from repo clut 8 at "
                  f"{len(diffs)} indices, e.g. index {diffs[0][0]}: "
                  f"palette {diffs[0][1]} vs clut 8 {diffs[0][2]}; the runtime "
                  f"interprets colour indices against clut 8, so Finder "
                  f"colours may differ from Aseprite", file=sys.stderr)
    explicit = {32: (args.png32_color, args.png32_1bit),
                16: (args.png16_color, args.png16_1bit)}
    sizes = [int(s) for s in args.sizes.split(",")] if args.sizes else [32, 16]
    for s in sizes:
        if s not in (32, 16):
            raise ConvertError(f"--sizes must be 32 and/or 16, got {s}")
    pngs = {}
    for size in sizes:
        color, mono = explicit[size]
        if not color and not mono and args.png_dir and args.family:
            color = os.path.join(args.png_dir, f"{args.family}-{size}-color.png")
            mono = os.path.join(args.png_dir, f"{args.family}-{size}-1bit.png")
        if not color or not mono:
            raise ConvertError(f"size {size}: need both a colour and a 1-bit PNG "
                               f"(pass --png{size}-color and --png{size}-1bit, "
                               f"or --png-dir with --family)")
        for p in (color, mono):
            if not os.path.isfile(p):
                raise ConvertError(f"size {size}: PNG not found: {p}")
        pngs[size] = (color, mono)
    new_bytes = {}
    report = []
    for size in sizes:
        color_path, mono_path = pngs[size]
        mono_img = _load_png_exact(mono_path, size)
        color_img = _load_png_exact(color_path, size)
        mono_bytes, mask = _mono_bytes(mono_img, size, args.snap,
                                       f"{mono_path} ({MONO[size]})")
        color_bytes = _color_bytes(color_img, mask, pal, size, args.snap,
                                   f"{color_path} ({COLOR[size]})", report)
        rb = size // 8
        back_color = color_icon(color_bytes, mono_bytes, pal, size)
        back_mono = bits_to_alpha(mono_bytes[:size * rb], mono_bytes[size * rb:],
                                  size, size, rb)
        # In --snap mode the expected image is the input with off-palette
        # colours snapped and coloured 1-bit pixels converted by luminance;
        # every other pixel must still match exactly.
        if args.snap:
            exp_color = Image.new("RGBA", (size, size), (0, 0, 0, 0))
            ep = exp_color.load(); cp = color_img.load(); mp = mono_img.load()
            index_of = {c: i for i, c in enumerate(pal)}
            for y in range(size):
                for x in range(size):
                    r, g, b, a = cp[x, y]
                    mr, mg, mb, ma = mp[x, y]
                    if ma < 128 or a < 128:
                        continue
                    rgb = (r, g, b)
                    if rgb not in index_of:
                        rgb = pal[nearest(pal, rgb)]
                    ep[x, y] = rgb + (255,)
            exp_mono = Image.new("RGBA", (size, size), (0, 0, 0, 0))
            ep = exp_mono.load()
            for y in range(size):
                for x in range(size):
                    r, g, b, a = mp[x, y]
                    if a < 128:
                        continue
                    v = 0 if (0.299 * r + 0.587 * g + 0.114 * b) < 170 else 255
                    ep[x, y] = (v, v, v, 255)
            checks = ((back_color, exp_color, "colour"),
                      (back_mono, exp_mono, "1-bit"))
        else:
            checks = ((back_color, color_img, "colour"),
                      (back_mono, mono_img, "1-bit"))
        for back, orig, name in checks:
            bp, op = back.load(), orig.load()
            for y in range(size):
                for x in range(size):
                    if bp[x, y] != op[x, y]:
                        raise ConvertError(
                            f"size {size} {name}: round-trip mismatch at "
                            f"({x},{y}): generated {bp[x, y]} vs input "
                            f"{op[x, y]}; refusing to write")
        new_bytes[MONO[size]] = mono_bytes
        new_bytes[COLOR[size]] = color_bytes
        report.append(f"size {size}: {MONO[size]} {len(mono_bytes)} bytes, "
                      f"{COLOR[size]} {len(color_bytes)} bytes, round-trip exact")
    bndl_note = _check_bndl(man, base_dir, args.id)
    if args.dry_run:
        print("\n".join(report))
        print(bndl_note)
        print("dry run: nothing written")
        return
    siblings = [r for r in man["resources"] if r.get("type") in
                ("ICN#", "icl8", "ics#", "ics8")]
    default_format = None
    for r in siblings:
        fmt = r.get("payload", {}).get("format")
        if fmt in ("hex", "file"):
            default_format = fmt
            break
    if default_format is None:
        default_format = "hex"
    changed = []
    for typ, raw in new_bytes.items():
        found = None
        for r in man["resources"]:
            if r.get("type") == typ and r.get("id") == args.id:
                found = r
                break
        if found is not None:
            fmt = found.get("payload", {}).get("format")
            if fmt == "hex":
                found["payload"] = {"format": "hex", "hex": raw.hex()}
            elif fmt == "file":
                path = os.path.join(base_dir, found["payload"]["path"])
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "wb") as f:
                    f.write(raw)
            else:
                raise ConvertError(f"{typ} {args.id}: unsupported payload "
                                   f"format {fmt!r}")
            changed.append(f"replaced {typ} {args.id} ({fmt})")
        else:
            symbol = _symbol_for(man, typ, args.id, args.family)
            if default_format == "hex":
                payload = {"format": "hex", "hex": raw.hex()}
            else:
                rel = os.path.join("assets", "visual",
                                   f"{TYPEHEX[typ]}-{args.id}.bin")
                path = os.path.join(base_dir, rel)
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "wb") as f:
                    f.write(raw)
                payload = {"format": "file", "path": rel}
            man["resources"].append({"type": typ, "id": args.id,
                                     "symbol": symbol, "payload": payload})
            changed.append(f"added {typ} {args.id} as {symbol} ({default_format})")
    out_path = args.out or args.resources
    if out_path == args.resources:
        bak = args.resources + ".bak"
        shutil.copyfile(args.resources, bak)
        print(f"backup of original: {bak}")
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(man, f, indent=2)
        f.write("\n")
    print(f"palette: {pal_name} ({len(pal)} colours)")
    print("\n".join(report))
    print(bndl_note)
    print("\n".join(changed))
    print(f"wrote {out_path}")
    print("next: rebuild the platform image so the extension is installed "
          "into System Folder/Extensions, then reboot; Finder and the "
          "startup strip both read this same family")

def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    ef = sub.add_parser("export")
    ef.add_argument("--resources", required=True)
    ef.add_argument("--id", type=int, required=True)
    ef.add_argument("--palette"); ef.add_argument("--repo")
    ef.add_argument("--family"); ef.add_argument("--out", required=True)
    inf = sub.add_parser("import")
    inf.add_argument("--resources", required=True)
    inf.add_argument("--id", type=int, required=True)
    inf.add_argument("--palette"); inf.add_argument("--repo")
    inf.add_argument("--png-dir"); inf.add_argument("--family")
    inf.add_argument("--png32-color"); inf.add_argument("--png32-1bit")
    inf.add_argument("--png16-color"); inf.add_argument("--png16-1bit")
    inf.add_argument("--sizes", default="32,16")
    inf.add_argument("--snap", action="store_true")
    inf.add_argument("--dry-run", action="store_true")
    inf.add_argument("--out")
    a = ap.parse_args()
    try:
        if a.cmd == "export":
            do_export(a)
        elif a.cmd == "import":
            do_import(a)
    except ConvertError as e:
        print(f"iconfamily: error: {e}", file=sys.stderr)
        sys.exit(2)

if __name__ == "__main__":
    main()
