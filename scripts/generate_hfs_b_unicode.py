#!/usr/bin/env python3
"""Regenerate pinned HFS-B name tables from Unicode 17.0.0 official data.

Downloads/cache and conformance corpus stay outside the OS repository. The
checked-in tables make ordinary builds deterministic and entirely offline.
"""
from pathlib import Path
import hashlib
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
CACHE = ROOT.parent / 'build' / 'system7' / 'unicode-17.0.0'
BASE = 'https://www.unicode.org/Public/17.0.0/ucd/'


def fetch(name):
    path = CACHE / name
    if not path.exists():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(urllib.request.urlopen(BASE + name, timeout=45).read())
    return path.read_text(encoding='utf-8')


def main():
    sources = {name: fetch(name) for name in (
        'UnicodeData.txt', 'DerivedNormalizationProps.txt', 'CaseFolding.txt',
        'NormalizationTest.txt')}
    excluded = set()
    for line in sources['DerivedNormalizationProps.txt'].splitlines():
        fields = line.split('#')[0].strip().split(';')
        if len(fields) < 2 or fields[1].strip() != 'Full_Composition_Exclusion':
            continue
        bounds = fields[0].strip().split('..')
        excluded.update(range(int(bounds[0], 16), int(bounds[-1], 16) + 1))
    combining, decompose, compose, fold = [], [], [], []
    for line in sources['UnicodeData.txt'].splitlines():
        fields = line.split(';')
        code = int(fields[0], 16)
        if int(fields[3]):
            combining.append((code, int(fields[3])))
        if fields[5] and not fields[5].startswith('<'):
            parts = [int(n, 16) for n in fields[5].split()]
            decompose.append((code, parts))
            if len(parts) == 2 and code not in excluded:
                compose.append((parts[0], parts[1], code))
    for line in sources['CaseFolding.txt'].splitlines():
        fields = line.split('#')[0].strip().split(';')
        if len(fields) >= 3 and fields[1].strip() in ('C', 'F'):
            fold.append((int(fields[0], 16), [int(n, 16) for n in fields[2].split()]))
    lines = ['// Generated by scripts/generate_hfs_b_unicode.py; do not hand edit.',
             '// Unicode 17.0.0, Copyright 2025 Unicode, Inc. See UNICODE-LICENSE.txt.']
    for name in sorted(sources):
        digest = hashlib.sha256((CACHE / name).read_bytes()).hexdigest()
        lines.append(f'// {BASE}{name} sha256={digest}')
    lines += ['#[rustfmt::skip]', 'pub(super) static COMBINING: &[(u32, u8)] = &[']
    lines += [f'    (0x{code:x}, {value}),' for code, value in combining]
    lines += ['];']
    for name, rows in [('DECOMPOSE', decompose), ('FOLD', fold)]:
        lines += ['#[rustfmt::skip]', f'pub(super) static {name}: &[(u32, &[u32])] = &[']
        for code, parts in rows:
            values = ', '.join(f'0x{n:x}' for n in parts)
            lines.append(f'    (0x{code:x}, &[{values}]),')
        lines += ['];']
    lines += ['#[rustfmt::skip]', 'pub(super) static COMPOSE: &[(u32, u32, u32)] = &[']
    lines += [f'    (0x{a:x}, 0x{b:x}, 0x{c:x}),' for a, b, c in sorted(compose)]
    lines += ['];', '']
    (ROOT / 'crates/mac-hfs-b/src/names/tables.rs').write_text('\n'.join(lines))
    license_path = ROOT / 'crates/mac-hfs-b/UNICODE-LICENSE.txt'
    if not license_path.exists():
        license_path.write_bytes(urllib.request.urlopen(
            'https://www.unicode.org/license.txt', timeout=45).read())
    print(f'Generated Unicode 17.0.0 tables; official conformance corpus: {CACHE}')


if __name__ == '__main__':
    main()
